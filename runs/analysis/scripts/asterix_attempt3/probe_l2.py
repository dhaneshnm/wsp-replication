def show(name, prow, ents, net=NET):
    h1,h2,z,p = fwd(net, obs(prow, ents))
    y=prow-1
    extra = f" S={h2[y]:+.2f} U={h2[8+y]:+.2f} D={h2[16+y]:+.2f} V={h2[24+y]:+.2f}" if net is NET else ""
    print(f"{name:58s} logits n/u/d={z[0]:+6.2f}/{z[2]:+6.2f}/{z[4]:+6.2f}{extra} | {fmtp(p)}")
E=lambda r,c,right: (r,c,right,False)
G=lambda r,c,right: (r,c,right,True)
